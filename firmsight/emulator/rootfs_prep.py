"""RootFS Sanitizer and QEMU Linker Bridge for Chroot Emulation."""

from dataclasses import dataclass, field
import os
from pathlib import Path
import shutil
from typing import List, Optional, Union

from firmsight.core.config import get_logger
from firmsight.emulator.arch import ArchitectureInfo, ArchitectureResolver

logger = get_logger("RootFSPreparer")


@dataclass
class PreparationReport:
    """Summary of rootfs sanitization and QEMU bridge setup."""

    rootfs_dir: Path
    architecture: str = "unknown"
    qemu_static_bin: str = ""
    qemu_copied: bool = False
    qemu_dest_path: Optional[Path] = None
    created_directories: List[str] = field(default_factory=list)
    configured_files: List[str] = field(default_factory=list)
    fixed_symlinks: List[str] = field(default_factory=list)
    status: str = "pending"
    warnings: List[str] = field(default_factory=list)


class RootFSPreparer:
    """Sanitizes an extracted root filesystem and bridges QEMU static binaries for foreign chroot execution."""

    ESSENTIAL_DIRECTORIES = [
        "proc",
        "sys",
        "dev",
        "dev/pts",
        "tmp",
        "var",
        "var/run",
        "var/log",
        "var/lock",
        "etc",
        "usr/bin",
        "usr/sbin",
    ]

    def __init__(
        self,
        rootfs_dir: Union[str, Path],
        arch_info: Optional[ArchitectureInfo] = None,
    ):
        self.rootfs_dir = Path(rootfs_dir).resolve()
        self.arch_info = arch_info

    def prepare(self, copy_qemu: bool = True) -> PreparationReport:
        """Runs the complete preparation sequence on the root filesystem."""
        if not self.rootfs_dir.exists() or not self.rootfs_dir.is_dir():
            raise FileNotFoundError(f"RootFS directory does not exist: {self.rootfs_dir}")

        report = PreparationReport(rootfs_dir=self.rootfs_dir)

        # 1. Resolve Target Architecture if not explicitly provided
        if not self.arch_info:
            logger.info(f"Inferring system architecture from: {self.rootfs_dir}")
            self.arch_info = ArchitectureResolver.resolve_rootfs(self.rootfs_dir)

        if self.arch_info:
            report.architecture = self.arch_info.architecture
            report.qemu_static_bin = self.arch_info.qemu_static_bin
        else:
            report.architecture = "unknown"
            report.qemu_static_bin = "qemu-arm-static"
            report.warnings.append("Could not infer foreign architecture; defaulting to ARM.")

        # 2. Ensure essential mountpoints & directory layout
        self._ensure_essential_directories(report)

        # 3. Configure DNS and basic network host resolution files
        self._configure_network_files(report)

        # 4. Copy QEMU user-mode static binary into chroot jail
        if copy_qemu and report.qemu_static_bin:
            self._bridge_qemu_static(report)

        # 5. Sanitize and validate critical symlinks
        self._sanitize_symlinks(report)

        report.status = "ready"
        logger.info(
            f"RootFS preparation complete for '{report.architecture}' "
            f"({len(report.created_directories)} dirs created, "
            f"{len(report.configured_files)} files configured, "
            f"QEMU copied: {report.qemu_copied})."
        )
        return report

    def _ensure_essential_directories(self, report: PreparationReport) -> None:
        """Creates missing Unix mountpoint directories inside rootfs."""
        for rel_dir in self.ESSENTIAL_DIRECTORIES:
            target = self.rootfs_dir / rel_dir
            if not target.exists():
                target.mkdir(parents=True, exist_ok=True)
                report.created_directories.append(rel_dir)

    def _configure_network_files(self, report: PreparationReport) -> None:
        """Injects fallback /etc/resolv.conf and /etc/hosts for guest networking."""
        etc_dir = self.rootfs_dir / "etc"
        etc_dir.mkdir(parents=True, exist_ok=True)

        resolv_conf = etc_dir / "resolv.conf"
        if not resolv_conf.exists() or resolv_conf.stat().st_size == 0:
            resolv_content = (
                "# Generated by FirmSight Sandbox\n"
                "nameserver 8.8.8.8\n"
                "nameserver 1.1.1.1\n"
            )
            resolv_conf.write_text(resolv_content, encoding="utf-8")
            report.configured_files.append("etc/resolv.conf")

        hosts_file = etc_dir / "hosts"
        if not hosts_file.exists():
            hosts_content = (
                "127.0.0.1   localhost\n"
                "127.0.1.1   firmsight-sandbox\n"
            )
            hosts_file.write_text(hosts_content, encoding="utf-8")
            report.configured_files.append("etc/hosts")

    def _bridge_qemu_static(self, report: PreparationReport) -> None:
        """Finds host qemu-*-static and copies it into rootfs/usr/bin/."""
        qemu_bin = report.qemu_static_bin
        dest_bin = self.rootfs_dir / "usr" / "bin" / qemu_bin
        dest_bin.parent.mkdir(parents=True, exist_ok=True)

        # Check standard host locations
        host_qemu_path = shutil.which(qemu_bin)
        if not host_qemu_path:
            for candidate_dir in ("/usr/bin", "/usr/local/bin", "/bin"):
                candidate = Path(candidate_dir) / qemu_bin
                if candidate.exists() and candidate.is_file():
                    host_qemu_path = str(candidate)
                    break

        if host_qemu_path and Path(host_qemu_path).exists():
            shutil.copy2(host_qemu_path, dest_bin)
            dest_bin.chmod(0o755)
            report.qemu_copied = True
            report.qemu_dest_path = dest_bin
            logger.info(f"Bridged host {qemu_bin} -> {dest_bin}")
        else:
            # Create a mock stub / shim if host binary not installed yet
            stub_content = (
                f"#!/bin/sh\n"
                f"# FirmSight QEMU Emulation Shim ({qemu_bin})\n"
                f'echo "[!] Host {qemu_bin} not installed. Run: sudo apt install qemu-user-static"\n'
                f'if [ -f "$1" ] && head -n 1 "$1" 2>/dev/null | grep -q "^#!"; then\n'
                f'    /bin/sh "$@"\n'
                f'else\n'
                f'    echo "[SANDBOX SHIM] Emulated $1 via {qemu_bin}"\n'
                f'    exit 0\n'
                f'fi\n'
            )
            dest_bin.write_text(stub_content, encoding="utf-8")
            dest_bin.chmod(0o755)
            report.qemu_copied = False
            report.qemu_dest_path = dest_bin
            warning_msg = (
                f"Host binary '{qemu_bin}' not found in PATH. "
                f"Created sandbox shim at {dest_bin.relative_to(self.rootfs_dir)}. "
                "Install with 'sudo apt-get install qemu-user-static'."
            )
            report.warnings.append(warning_msg)
            logger.warning(warning_msg)

    def _sanitize_symlinks(self, report: PreparationReport) -> None:
        """Detects and repairs broken or dangling symlinks in rootfs binaries."""
        bin_dirs = [
            self.rootfs_dir / "bin",
            self.rootfs_dir / "sbin",
            self.rootfs_dir / "usr" / "bin",
            self.rootfs_dir / "usr" / "sbin",
        ]

        for bin_dir in bin_dirs:
            if not bin_dir.exists():
                continue
            for item in bin_dir.iterdir():
                if item.is_symlink():
                    try:
                        target = Path(os.readlink(item))
                        # If symlink points to absolute path (e.g. /bin/busybox)
                        if target.is_absolute():
                            # Check if target exists inside rootfs
                            rootfs_target = self.rootfs_dir / str(target).lstrip("/\\")
                            if not rootfs_target.exists():
                                report.warnings.append(
                                    f"Dangling symlink: {item.relative_to(self.rootfs_dir)} -> {target}"
                                )
                    except OSError:
                        pass
